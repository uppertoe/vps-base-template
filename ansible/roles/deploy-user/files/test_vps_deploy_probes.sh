#!/bin/bash
# Test of vps-deploy-probes, the post-deploy acceptance probes (docs/05). Runs
# anywhere with bash and awk, no root and no network:
#   bash ansible/roles/deploy-user/files/test_vps_deploy_probes.sh
# curl is a stub that answers from a table of "host<TAB>header<TAB>status<TAB>
# location" lines, so each scenario sets what the local Caddy would say and
# the test checks the verdict, the exit status and the notification.
# shellcheck disable=SC2016  # the single-quoted $1/$2 belong to the stub, and the {$DOMAIN} forms are literal Caddy placeholders
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
fail() { echo "FAIL: $*"; exit 1; }
ok() { echo "ok: $*"; }

mkdir -p "$work/bin" "$work/stack/.generated/caddy"
# The stub reads the host from --resolve and the extra header from -H, finds
# the matching table row and prints the -w format as curl would. A host with
# no row gets no answer (exit 7, status 000), as a refused connection would.
cat >"$work/bin/curl" <<'EOF'
#!/bin/bash
host=""; header=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --resolve) host="${2%%:*}"; shift 2 ;;
    -H) header="$2"; shift 2 ;;
    -A|--max-time|--connect-timeout|-o|-w) shift 2 ;;
    *) shift ;;
  esac
done
echo "curl $host ${header:--}" >>"$CURL_LOG"
row="$(awk -F'\t' -v h="$host" -v hd="${header:--}" '$1 == h && $2 == hd { print $3 "\t" $4; exit }' "$CURL_TABLE")"
if [[ -z "$row" ]]; then printf '000\t'; exit 7; fi
printf '%s' "$row"
EOF
printf '#!/bin/bash\nprintf "notify: %%s\\n" "$1" >>"$NOTIFY_LOG"\nprintf "%%s\\n" "$2" >>"$NOTIFY_LOG"\n' >"$work/bin/vps-notify"
chmod 0755 "$work/bin/curl" "$work/bin/vps-notify"
export CURL_LOG="$work/curl.log" CURL_TABLE="$work/answers.tsv" NOTIFY_LOG="$work/notify.log"
export VPS_DEPLOY_PROBES_NOTIFY="$work/bin/vps-notify" VPS_DEPLOY_PROBES_ATTEMPTS=2 VPS_DEPLOY_PROBES_RETRY_WAIT=0

stack="$work/stack"
table="$stack/.generated/caddy/route-access.tsv"
printf 'DOMAIN=example.org\n' >"$stack/.env"
run() {
  : >"$CURL_LOG"; : >"$NOTIFY_LOG"
  PATH="$work/bin:$PATH" "$BASH" "$here/vps-deploy-probes" "$stack" >"$work/out.log" 2>&1
}
answers() { printf '%s\n' "$@" | tr '|' '\t' >"$CURL_TABLE"; }

# 1. A healthy estate: public sites answer below 500, gated sites send
#    302 to the gateway with or without a forged identity header, a mixed site
#    or a public site with no root route may answer 404, and a site on a named
#    network is treated as open. Comma-separated addresses are probed one host at a time.
cat >"$table" <<'EOF'
# Generated by scaffold/docker/render-caddy-routes.sh; do not edit.
# Access rules per site, one "host<TAB>kind<TAB>value" per line.
auth.{$DOMAIN}	public	the sign-in service itself
docs.{$DOMAIN}	domains	example.org
hooks.{$DOMAIN}	domains	example.org
hooks.{$DOMAIN}	public	/*: every other path on this host is answered 404
planka.{$DOMAIN}	groups	planka-users
www.{$DOMAIN},{$DOMAIN}	public	the homepage
caffeine.{$DOMAIN}	network	mch
ntfy.{$DOMAIN}	public	the app strips the shared cookie itself; its root has no route
EOF
answers 'auth.example.org|-|200|' \
        'docs.example.org|-|302|https://auth.example.org/login?rd=https%3A%2F%2Fdocs.example.org%2F' \
        'docs.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login?rd=x' \
        'hooks.example.org|-|404|' \
        'planka.example.org|-|302|https://auth.example.org/login' \
        'planka.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'www.example.org|-|302|https://example.org/' \
        'example.org|-|200|' \
        'caffeine.example.org|-|200|' \
        'ntfy.example.org|-|404|'
run || fail "a healthy estate failed: $(cat "$work/out.log")"
grep -q 'ok   ntfy.example.org (404)' "$work/out.log" || fail "a public site whose root has no route must pass on 404: $(cat "$work/out.log")"
grep -q '8 site(s) answered' "$work/out.log" || fail "expected eight probed sites: $(cat "$work/out.log")"
grep -q 'curl docs.example.org Remote-Email: forged@example.invalid' "$CURL_LOG" || fail "no forged-identity probe for the gated site"
grep -q 'curl hooks.example.org Remote-Email' "$CURL_LOG" && fail "a mixed site got a forged-identity probe"
[[ ! -s "$NOTIFY_LOG" ]] || fail "a passing run notified"
ok "a healthy estate passes, with a forged-identity probe on every gated site only"

# 2. A gated site that answers 200 to a forged identity header fails, and the
#    notification names the host and the forged probe.
answers 'auth.example.org|-|200|' 'ntfy.example.org|-|404|' \
        'docs.example.org|-|302|https://auth.example.org/login?rd=x' \
        'docs.example.org|Remote-Email: forged@example.invalid|200|' \
        'hooks.example.org|-|404|' \
        'planka.example.org|-|302|https://auth.example.org/login' \
        'planka.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'www.example.org|-|302|https://example.org/' 'example.org|-|200|' 'caffeine.example.org|-|200|'
if run; then fail "a forged identity answered by the app passed"; fi
grep -q 'FAIL docs.example.org with a forged identity header: answered 200' "$work/out.log" || fail "the forged-identity failure was not reported: $(cat "$work/out.log")"
grep -q 'notify: Deploy probes failed on 1 site(s)' "$NOTIFY_LOG" || fail "no notification: $(cat "$NOTIFY_LOG")"
grep -q 'docs.example.org (forged identity header)' "$NOTIFY_LOG" || fail "the notification does not name the host"
ok "a gated site that honours a forged identity header fails and is notified"

# 3. A gated site that answers 200 without any header fails; a 302 anywhere
#    but the gateway's /login fails too; a 5xx on a public site fails; a site
#    with no answer fails; the retry is used before each verdict.
answers 'auth.example.org|-|503|' 'ntfy.example.org|-|404|' \
        'docs.example.org|-|200|' \
        'docs.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'hooks.example.org|-|404|' \
        'planka.example.org|-|302|https://planka.example.org/boards' \
        'planka.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'www.example.org|-|302|https://example.org/' 'caffeine.example.org|-|200|'
if run; then fail "an estate with four broken sites passed"; fi
grep -q 'FAIL auth.example.org: answered 503' "$work/out.log" || fail "the 5xx on a public site was not reported"
grep -q 'FAIL docs.example.org: answered 200' "$work/out.log" || fail "the open gated site was not reported"
grep -q 'FAIL planka.example.org: answered 302 -> https://planka.example.org/boards' "$work/out.log" || fail "a redirect away from the gateway was not reported"
grep -q 'FAIL example.org: no answer from the local Caddy' "$work/out.log" || fail "the unanswered site was not reported: $(cat "$work/out.log")"
grep -q 'notify: Deploy probes failed on 4 site(s)' "$NOTIFY_LOG" || fail "the notification does not count four failures: $(cat "$NOTIFY_LOG")"
[[ "$(grep -c '^curl example.org -$' "$CURL_LOG")" == 2 ]] || fail "the unanswered site was not retried"
ok "open gates, redirects away from the gateway, 5xx answers and silence all fail"

# 4. A mixed site answering 5xx fails; the same site answering 404 passed in 1.
answers 'auth.example.org|-|200|' 'ntfy.example.org|-|404|' \
        'docs.example.org|-|302|https://auth.example.org/login' \
        'docs.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'hooks.example.org|-|502|' \
        'planka.example.org|-|302|https://auth.example.org/login' \
        'planka.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'www.example.org|-|302|https://example.org/' 'example.org|-|200|' 'caffeine.example.org|-|200|'
if run; then fail "a mixed site answering 502 passed"; fi
grep -q 'FAIL hooks.example.org: answered 502 (expected an answer below 500)' "$work/out.log" || fail "the mixed-site 502 was not reported: $(cat "$work/out.log")"
ok "a mixed site fails on 5xx only"

# 5. deploy-probes.skip takes a host out of the run, by resolved name or by
#    address form, and the reason is shown; a placeholder without a value and
#    an address that is not a plain host are skipped with a note.
cat >"$stack/deploy-probes.skip" <<'EOF'
# host  reason
docs.example.org   DNS points at the old host until the cut-over on Friday
planka.{$DOMAIN}   Planka is not yet deployed here
EOF
cat >>"$table" <<'EOF'
legacy.{$OTHER}	public	no value for the placeholder
http://plain.{$DOMAIN}	public	served over http
EOF
answers 'auth.example.org|-|200|' 'ntfy.example.org|-|404|' 'hooks.example.org|-|404|' \
        'www.example.org|-|302|https://example.org/' 'example.org|-|200|' 'caffeine.example.org|-|200|'
run || fail "skips were not honoured: $(cat "$work/out.log")"
grep -q 'skip docs.example.org: DNS points at the old host until the cut-over on Friday (deploy-probes.skip)' "$work/out.log" || fail "the skip reason is not shown: $(cat "$work/out.log")"
grep -q 'skip planka.example.org: Planka is not yet deployed here' "$work/out.log" || fail "a skip by address form was not honoured"
grep -q 'skip legacy.{$OTHER}: a placeholder in the address has no value' "$work/out.log" || fail "an unresolved placeholder was not skipped"
grep -q 'skip http://plain.{$DOMAIN}: not a plain https host name' "$work/out.log" || fail "an http address was not skipped"
grep -q 'curl docs.example.org' "$CURL_LOG" && fail "a skipped host was probed"
grep -q '6 site(s) answered' "$work/out.log" || fail "expected six probed sites after the skips: $(cat "$work/out.log")"
ok "deploy-probes.skip, unresolved placeholders and non-host addresses are skipped with a note"
rm -f "$stack/deploy-probes.skip"

# 6. The caller words the outcome. VPS_DEPLOY_PROBES_OUTCOME closes the log
#    and the alert; an empty VPS_DEPLOY_PROBES_NOTIFY sends no alert; and
#    VPS_DEPLOY_PROBES_FAILED_FILE receives the failing hosts, one per line,
#    or an empty file when every probe passed.
answers 'auth.example.org|-|503|' 'ntfy.example.org|-|404|' 'hooks.example.org|-|404|' \
        'docs.example.org|-|302|https://auth.example.org/login' \
        'docs.example.org|Remote-Email: forged@example.invalid|200|' \
        'planka.example.org|-|302|https://auth.example.org/login' \
        'planka.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'www.example.org|-|302|https://example.org/' 'example.org|-|200|' 'caffeine.example.org|-|200|'
if VPS_DEPLOY_PROBES_OUTCOME="The deploy is live; this is the caller's sentence." run; then fail "two broken sites passed"; fi
grep -q "^vps-deploy-probes: The deploy is live; this is the caller's sentence.$" "$work/out.log" || fail "the caller's outcome was not printed: $(cat "$work/out.log")"
grep -q "^The deploy is live; this is the caller's sentence. Details are in the deploy log" "$NOTIFY_LOG" || fail "the caller's outcome is not in the alert: $(cat "$NOTIFY_LOG")"
grep -q 'has not been rolled back' "$NOTIFY_LOG" && fail "the default outcome was sent as well as the caller's"
if run; then fail "two broken sites passed"; fi
grep -q '^The deploy is live and has not been rolled back. Details' "$NOTIFY_LOG" || fail "the default outcome is missing: $(cat "$NOTIFY_LOG")"
if VPS_DEPLOY_PROBES_NOTIFY="" VPS_DEPLOY_PROBES_FAILED_FILE="$work/failed" run; then fail "two broken sites passed"; fi
[[ ! -s "$NOTIFY_LOG" ]] || fail "an alert was sent although the notifier was set empty: $(cat "$NOTIFY_LOG")"
[[ "$(cat "$work/failed")" == $'auth.example.org\ndocs.example.org (forged identity header)' ]] || fail "the failed-hosts file is wrong: $(cat "$work/failed")"
answers 'auth.example.org|-|200|' 'ntfy.example.org|-|404|' 'hooks.example.org|-|404|' \
        'docs.example.org|-|302|https://auth.example.org/login' \
        'docs.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'planka.example.org|-|302|https://auth.example.org/login' \
        'planka.example.org|Remote-Email: forged@example.invalid|302|https://auth.example.org/login' \
        'www.example.org|-|302|https://example.org/' 'example.org|-|200|' 'caffeine.example.org|-|200|'
VPS_DEPLOY_PROBES_FAILED_FILE="$work/failed" run || fail "a healthy estate failed: $(cat "$work/out.log")"
[[ -f "$work/failed" && ! -s "$work/failed" ]] || fail "a passing run did not leave an empty failed-hosts file"
ok "the caller's outcome is used, an empty notifier sends nothing, and the failing hosts are written to the file"

# 7. No access table means nothing to probe, and a clean exit.
rm -f "$table"
run || fail "a stack without an access table failed: $(cat "$work/out.log")"
grep -q 'nothing to probe' "$work/out.log" || fail "the missing table was not reported"
[[ ! -s "$CURL_LOG" ]] || fail "curl was called without a table"
ok "no access table: nothing to probe"

echo "all vps-deploy-probes checks passed"
